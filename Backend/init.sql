CREATE TABLE IF NOT EXISTS public.clubs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coordenadas character varying(255),
    deporte_adaptado boolean,
    descripcion character varying(255),
    direccion character varying(255) NOT NULL,
    disciplinas character varying(255),
    email character varying(255),
    horarios character varying(255),
    nombre_institucion character varying(255) NOT NULL,
    sitio_web_url character varying(255),
    telefono character varying(255)
);

CREATE TABLE IF NOT EXISTS public.club_fotos (
    club_id bigint NOT NULL,
    foto_url character varying(255),
    CONSTRAINT fkdajrylbyp940tndte4r8gtnja FOREIGN KEY (club_id) REFERENCES public.clubs(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.deportistas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deporte character varying(255) NOT NULL,
    deporte_adaptado boolean,
    edad integer,
    email character varying(255),
    historia text,
    logros text,
    nombre character varying(255) NOT NULL,
    sitio_web_url character varying(255),
    telefono character varying(255),
    club_id bigint,
    CONSTRAINT deportistas_edad_check CHECK (edad >= 1),
    CONSTRAINT fknuu8dr7saetny2vkffb6o3l57 FOREIGN KEY (club_id) REFERENCES public.clubs(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.deportista_fotos (
    deportista_id bigint NOT NULL,
    foto_url character varying(255),
    CONSTRAINT fkpsyri7qxnjogdrhqoe9eneuxi FOREIGN KEY (deportista_id) REFERENCES public.deportistas(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.solicitudes_registro (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    datos_adjuntos text NOT NULL,
    estado character varying(255) NOT NULL,
    fecha_envio timestamp(6) without time zone NOT NULL,
    fecha_revision timestamp(6) without time zone,
    motivo_rechazo text,
    perfil_creado_id bigint,
    tipo character varying(255) NOT NULL,
    CONSTRAINT solicitudes_registro_estado_check CHECK (estado::text = ANY (ARRAY['PENDIENTE'::character varying, 'APROBADO'::character varying, 'RECHAZADO'::character varying]::text[])),
    CONSTRAINT solicitudes_registro_tipo_check CHECK (tipo::text = ANY (ARRAY['CLUB'::character varying, 'DEPORTISTA'::character varying]::text[]))
);

