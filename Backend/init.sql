CREATE TABLE IF NOT EXISTS public.admin (
    id bigint NOT NULL,
    email character varying(255),
    password character varying(255) NOT NULL,
    usuario character varying(255) NOT NULL,
    CONSTRAINT admin_pkey PRIMARY KEY (id)
